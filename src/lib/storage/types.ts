/**
 * The storage contract the application codes against.
 *
 * Three backends implement it: local disk (development and the existing
 * self-hosted server), Cloudinary (the current production backend) and Supabase
 * Storage (the target). Nothing above this line knows which one is in use.
 *
 * Two boundaries matter and are deliberately *not* inside this interface:
 *
 *   - **Validation.** Sniffing magic bytes, enforcing the accepted-type list and
 *     the size cap happen in the upload route before any backend is called. A
 *     backend is handed bytes that are already known to be a real image of the
 *     declared type. Putting validation behind the interface would mean three
 *     chances to get it subtly wrong instead of one.
 *
 *   - **Naming.** Keys are generated by the shared module so every backend
 *     produces the same `<timestamp>-<hex>.<ext>` shape. That shape is an
 *     allowlist which blocks path traversal, so it is a security property rather
 *     than a convention, and it must not vary by backend.
 *
 * `Content-Type` is returned by `get` and is expected to come from a fixed table
 * keyed on the key's extension, never from anything a client supplied.
 */

export type StorageBackendName = "local" | "cloudinary" | "supabase";

/** Where an object ended up, and how to get back to it. */
export type StoredObject = {
  /**
   * Opaque identifier used by `get` and `remove`.
   *
   * For local and Supabase this is the stored filename. Cloudinary returns its
   * own `public_id`, which is why this is not simply the filename.
   */
  key: string;
  /**
   * Absolute or root-relative URL the browser can load.
   *
   * This is the only field the CMS persists and renders, so its shape is part of
   * the public contract of the site: changing a backend must not change how
   * already-stored URLs behave.
   */
  url: string;
};

export type PutInput = {
  key: string;
  body: Buffer;
  /** Already validated against the accepted-type list. */
  contentType: string;
  /**
   * Logical grouping, e.g. `kalisizo-coffee/editor`. Cloudinary turns this into
   * a folder; the others record it as object metadata. Purely organisational —
   * it must never become part of a URL or a key.
   */
  folder?: string;
};

export type GetResult = {
  body: ReadableStream<Uint8Array>;
  /** From the fixed extension table. Never from a request header. */
  contentType: string;
  /** Absent when the backend cannot report it cheaply. */
  size?: number;
  etag?: string;
};

export interface StorageBackend {
  readonly name: StorageBackendName;

  /**
   * Stores an object. Implementations must not overwrite an existing key:
   * generated keys include a timestamp and random suffix, so a collision means a
   * bug worth surfacing rather than silently replacing someone's image.
   */
  put(input: PutInput): Promise<StoredObject>;

  /** Resolves null when the object does not exist. */
  get(key: string): Promise<GetResult | null>;

  /**
   * Removes an object.
   *
   * Deleting something already gone is success, not an error: the CMS's delete
   * button has no undo, and a retry after a partial failure must not report a
   * failure that means nothing.
   */
  remove(key: string): Promise<void>;
}

/**
 * Raised by a backend for a failure the caller should surface as a retryable
 * error. Anything else escaping `put`/`get`/`remove` is a bug.
 */
export class StorageError extends Error {
  constructor(
    message: string,
    readonly cause?: unknown
  ) {
    super(message);
    this.name = "StorageError";
  }
}